@pytest.mark.parametrize(
    "message,expected_seconds",
    [
        ("Please try again in 9m26.784s.", 566.784),
        ("Please try again in 10m37.632s.", 637.632),
        ("Please try again in 5.2s.", 5.2),
        ("no timing info here", 30.0),
    ],
)
def test_parse_retry_after_seconds(message, expected_seconds):
    assert run_llm_eval._parse_retry_after_seconds(message) == pytest.approx(expected_seconds)


def test_generate_sql_with_retry_retries_on_429_then_succeeds(monkeypatch):
    calls = {"n": 0}

    def fake_chat_fn(_system, _user):
        calls["n"] += 1
        if calls["n"] == 1:
            raise ApiUnavailableError("HTTP 429: rate_limit_exceeded. Please try again in 0.01s.")
        return ChatCompletion(content="```sql\nSELECT 1\n```", usage={"total_tokens": 5})

    monkeypatch.setattr(run_llm_eval.time, "sleep", lambda _s: None)  # don't actually wait in tests
    sql, usage = run_llm_eval.generate_sql_with_retry(fake_chat_fn, "system", "context", "question")
    assert sql == "SELECT 1"
    assert calls["n"] == 2


def test_generate_sql_with_retry_reraises_non_429_immediately(monkeypatch):
    calls = {"n": 0}

    def fake_chat_fn(_system, _user):
        calls["n"] += 1
        raise ApiUnavailableError("HTTP 500: internal server error")

    with pytest.raises(ApiUnavailableError):
        run_llm_eval.generate_sql_with_retry(fake_chat_fn, "system", "context", "question")
    assert calls["n"] == 1  # no retry for non-429 errors


def test_generate_sql_with_retry_gives_up_after_max_retries(monkeypatch):
    def always_rate_limited(_system, _user):
        raise ApiUnavailableError("HTTP 429: rate_limit_exceeded. Please try again in 0.01s.")

    monkeypatch.setattr(run_llm_eval.time, "sleep", lambda _s: None)
    with pytest.raises(ApiUnavailableError):
        run_llm_eval.generate_sql_with_retry(always_rate_limited, "system", "context", "question", max_retries=2)

pytestmark = pytest.mark.skipif(not DUCKDB_PATH.exists(), reason="warehouse not built yet")


@pytest.mark.parametrize(
    "actual,expected,should_match",
    [
        ([(150000,)], [[150000]], True),
        ([(1, "a"), (2, "b")], [[2, "b"], [1, "a"]], True),  # order-insensitive
        ([(1,)], [[2]], False),
        ([], [], True),
        ([(1,)], [], False),
    ],
)
def test_results_match(actual, expected, should_match):
    assert run_llm_eval.results_match(actual, expected) == should_match


