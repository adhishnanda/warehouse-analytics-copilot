"""Light tests for the retrieval evaluation script's scoring logic and
report shape. Not a re-check of the actual measured numbers (those live in
evaluation/results/retrieval_eval.md, generated by running the script) —
just that the machinery is correct.
"""

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import evaluation.run_retrieval_eval as run_retrieval_eval
from src.config import DUCKDB_PATH
from src.retrieval.indexer import INDEX_PATH

pytestmark = pytest.mark.skipif(
    not (DUCKDB_PATH.exists() and INDEX_PATH.exists() and run_retrieval_eval.GOLDEN_PATH.exists()),
    reason="warehouse/index/golden set not built yet",
)


def test_load_golden_questions_returns_50():
    questions = run_retrieval_eval.load_golden_questions()
    assert len(questions) == 50


@pytest.mark.parametrize(
    "ranked,relevant,expected_hit,expected_rr",
    [
        (["a", "b", "c"], {"b"}, 1, 0.5),
        (["a", "b", "c"], {"a"}, 1, 1.0),
        (["a", "b", "c"], {"z"}, 0, 0.0),
        ([], {"a"}, 0, 0.0),
        (["a", "b"], {"a", "b"}, 1, 1.0),  # earliest relevant hit wins
    ],
)
def test_hit_and_reciprocal_rank(ranked, relevant, expected_hit, expected_rr):
    hit, rr = run_retrieval_eval.hit_and_reciprocal_rank(ranked, relevant)
    assert hit == expected_hit
    assert rr == expected_rr


def test_evaluate_method_with_perfect_retriever_scores_1():
    questions = run_retrieval_eval.load_golden_questions()

    def perfect_fn(question: str) -> list[str]:
        for q in questions:
            if q["question"] == question:
                return q["relevant_doc_ids"]
        return []

    result = run_retrieval_eval.evaluate_method("perfect", perfect_fn, questions)
    assert result["hit_rate"] == 1.0
    assert result["mrr"] == 1.0
    assert set(result["per_tier"].keys()) == {1, 2, 3}


def test_evaluate_method_with_useless_retriever_scores_0():
    questions = run_retrieval_eval.load_golden_questions()

    def useless_fn(_question: str) -> list[str]:
        return ["nonexistent:doc"]

    result = run_retrieval_eval.evaluate_method("useless", useless_fn, questions)
    assert result["hit_rate"] == 0.0
    assert result["mrr"] == 0.0


def test_results_file_was_generated_with_all_four_methods():
    content = run_retrieval_eval.RESULTS_PATH.read_text(encoding="utf-8")
    for method in ["Keyword only", "Vector only", "Hybrid", "Hybrid + rerank"]:
        assert method in content
    assert "Best approach used in production" in content
