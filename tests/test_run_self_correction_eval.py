"""Tests for the self-correction evaluation script's scoring logic. Not a
re-check of the actual measured lift (that lives in
evaluation/results/self_correction_eval.md, generated by running the
script against the real gpt-4o-mini agent loop) — just that the
rescued/regressed/summary machinery is correct.
"""

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import evaluation.run_self_correction_eval as run_self_correction_eval
from src.config import DUCKDB_PATH

pytestmark = pytest.mark.skipif(not DUCKDB_PATH.exists(), reason="warehouse not built yet")

QuestionOutcome = run_self_correction_eval.QuestionOutcome


def _outcome(tier=1, single=True, retry=True, retried=False, rescued=False, regressed=False):
    return QuestionOutcome(
        question_id="q",
        tier=tier,
        single_shot_correct=single,
        retry_correct=retry,
        retried=retried,
        rescued=rescued,
        regressed=regressed,
        attempt_count=2 if retried else 1,
    )


def test_summarize_computes_overall_and_per_tier_accuracy():
    outcomes = [
        _outcome(tier=1, single=True, retry=True),
        _outcome(tier=1, single=False, retry=False),
        _outcome(tier=2, single=False, retry=True, retried=True, rescued=True),
    ]
    summary = run_self_correction_eval.summarize(outcomes)
    assert summary["single_shot_accuracy"] == pytest.approx(1 / 3)
    assert summary["retry_accuracy"] == pytest.approx(2 / 3)
    assert summary["per_tier_single"][1] == pytest.approx(0.5)
    assert summary["per_tier_retry"][1] == pytest.approx(0.5)
    assert summary["per_tier_single"][2] == 0.0
    assert summary["per_tier_retry"][2] == 1.0


def test_summarize_counts_retried_rescued_regressed():
    outcomes = [
        _outcome(single=True, retry=True, retried=False),  # no retry needed
        _outcome(single=False, retry=True, retried=True, rescued=True),  # rescued
        _outcome(single=True, retry=False, retried=True, regressed=True),  # regressed
        _outcome(single=False, retry=False, retried=True),  # retried, still wrong
    ]
    summary = run_self_correction_eval.summarize(outcomes)
    assert summary["retried_count"] == 3
    assert summary["rescued_count"] == 1
    assert summary["regressed_count"] == 1


def test_evaluate_question_marks_rescued_when_retry_fixes_a_wrong_first_attempt(monkeypatch):
    from dataclasses import dataclass

    @dataclass
    class FakeResult:
        rows: list

    @dataclass
    class FakeAttempt:
        result: object
        error: object = None

    @dataclass
    class FakeResponse:
        attempts: list
        final_result: object

    fake_response = FakeResponse(
        attempts=[FakeAttempt(FakeResult([(999,)])), FakeAttempt(FakeResult([(150000,)]))],
        final_result=FakeResult([(150000,)]),
    )
    monkeypatch.setattr(run_self_correction_eval, "answer_question", lambda *a, **k: fake_response)

    q = {"id": "t1_01", "tier": 1, "question": "how many orders", "reference_result": [[150000]]}
    outcome = run_self_correction_eval.evaluate_question(q, con=None, retriever=None, reranker=None, chat_fn=None)

    assert outcome.single_shot_correct is False
    assert outcome.retry_correct is True
    assert outcome.retried is True
    assert outcome.rescued is True
    assert outcome.regressed is False


def test_results_file_was_generated_with_expected_sections():
    content = run_self_correction_eval.RESULTS_PATH.read_text(encoding="utf-8")
    assert "Single-shot (no retry)" in content
